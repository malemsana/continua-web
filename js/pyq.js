    function renderPyqs(data, closeDrawerFn){
      const container = document.getElementById('pyqBookContent');
      const drawerBody = document.getElementById('drawerBody');
      if(!container) return;
      const groups = (data.groups || []).slice().sort((a,b)=> (a.displayOrder||0)-(b.displayOrder||0));
      if(groups.length===0){
        container.innerHTML = '<div class="empty-state"><strong>No past year questions available</strong><br>PYQs for this chapter will appear here when published.</div>';
        if(drawerBody) drawerBody.innerHTML = '<div style="font-size:0.85rem;color:var(--color-text-muted);">No questions</div>';
        return;
      }
      let html = '';
      let drawerHtml = '';
      groups.forEach((group, gIdx)=>{
        const groupTitle = group.friendlyName || group.id;
        const groupAnchorId = 'pyq-group-' + (group.id || gIdx);
        const questions = (group.questions || []).slice().sort((a,b)=> (a.displayOrder||0)-(b.displayOrder||0));
        // Drawer group
        drawerHtml += '<div class="drawer-group"><div class="drawer-group-title"><span>' + escapeAttr(groupTitle) + '</span><span style="font-size:0.72rem;color:#64748b;font-weight:normal;">' + questions.length + ' Qs</span></div><div class="drawer-q-grid">';
        questions.forEach((q)=>{
          const n = q.displayOrder;
          const qAnchorId = q.id || ('pyq-' + group.id + '-q' + n);
          const label = 'Q' + n;
          drawerHtml += '<a href="#' + qAnchorId + '" class="drawer-q-link" data-target="' + qAnchorId + '">' + label + '</a>';
        });
        drawerHtml += '</div></div>';

        // Main content group header
        html += '<section class="pyq-group" id="' + groupAnchorId + '">'
              + '<div class="pyq-group-header"><h2 class="pyq-group-title">' + escapeHtml(groupTitle) + '</h2></div>';

        if(questions.length===0){
          html += '<div class="empty-state">No questions in this group.</div>';
        } else {
          questions.forEach((q, idx)=>{
            const n = q.displayOrder;
            const qAnchorId = q.id || ('pyq-' + group.id + '-q' + n);
            let qHtml = '';
            if (window.ContinuaRenderer && window.ContinuaRenderer.renderMarkdown) {
              qHtml = window.ContinuaRenderer.renderMarkdown(q.questionText || '');
            } else {
              qHtml = (q.questionText||'').replace(/\n\n/g,'<br><br>');
            }
            let solHtml = '';
            if (window.ContinuaRenderer && window.ContinuaRenderer.renderMarkdown) {
              solHtml = window.ContinuaRenderer.renderMarkdown(q.solutionText || '');
            } else {
              solHtml = (q.solutionText||'').replace(/\n\n/g,'<br><br>');
            }
            // sourceInfo subtle
            const sourceHtml = q.sourceInfo ? '<span class="question-source">' + escapeHtml(q.sourceInfo) + '</span>' : '';
            // Options - do not expose isCorrect; selectable only in Try First
            let optionsHtml = '';
            if (q.options && Array.isArray(q.options) && q.options.length>0) {
              optionsHtml = '<div class="example-options" role="radiogroup" aria-label="Answer choices for Question ' + n + '">';
              q.options.forEach((opt, oi)=>{
                const label = String.fromCharCode(65+oi);
                let optText = typeof opt === 'string' ? opt : (opt.text || opt.label || '');
                if (window.ContinuaRenderer && window.ContinuaRenderer.renderMarkdown) {
                  optText = window.ContinuaRenderer.renderMarkdown(optText).replace(/^<p>/,'').replace(/<\/p>$/,'');
                } else {
                  optText = escapeHtml(optText);
                }
                optionsHtml += '<button type="button" class="option-choice" role="radio" aria-checked="false" data-opt="' + oi + '" aria-label="Option ' + label + '"><span class="options-label">' + label + '.</span><span class="option-text">' + optText + '</span></button>';
              });
              optionsHtml += '</div>';
            }
            const solutionId = 'solution-' + qAnchorId;
            html += '<article class="question-entry" id="' + qAnchorId + '" data-group="' + escapeAttr(group.id) + '" data-num="' + n + '">'
                  + '<div class="question-header"><h3 class="question-heading">Question ' + n + '</h3>' + sourceHtml + '</div>'
                  + '<div class="question-body">' + qHtml + '</div>'
                  + optionsHtml
                  + '<div class="try-first-controls"><button type="button" class="show-solution-btn" aria-expanded="false" aria-controls="' + solutionId + '"><span>Show Solution</span><svg class="solution-chevron" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><polyline points="6 9 12 15 18 9"></polyline></svg></button></div>'
                  + '<div class="solution-block" id="' + solutionId + '"><span class="solution-label">Solution</span><div class="solution-content">' + solHtml + '</div></div>'
                  + '</article>';
            if(idx < questions.length-1) html += '<hr class="question-divider">';
          });
        }
        html += '</section>';
        if(gIdx < groups.length-1) html += '<hr class="pyq-group-divider">';
      });
      container.innerHTML = html;
      if(drawerBody) drawerBody.innerHTML = drawerHtml;
      if(drawerBody){
        drawerBody.querySelectorAll('.drawer-q-link').forEach(link=>{
          link.addEventListener('click', ()=>{
            if(window.innerWidth<=900 && closeDrawerFn) closeDrawerFn();
          });
        });
      }
      // Populate breadcrumb pickers
      populatePickers(groups);
      if(window.ContinuaRenderer && window.ContinuaRenderer.renderMath){
        window.ContinuaRenderer.renderMath(container);
      } else if(window.renderMathInElement){
        renderMathInElement(container, {delimiters:[{left:'$$',right:'$$',display:true},{left:'\\[',right:'\\]',display:true},{left:'\\(',right:'\\)',display:false},{left:'$',right:'$',display:false}],throwOnError:false});
      }
      setupScrollSpy(groups);
      handleHash();
      window.addEventListener('hashchange', handleHash);
    }

